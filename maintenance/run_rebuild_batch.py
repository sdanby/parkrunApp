def to_iso(date_str):
    return datetime.strptime(date_str, "%d/%m/%Y").strftime("%Y-%m-%d")


def main():
    for date_dd, event_code, event_number in ROWS:
        iso = to_iso(date_dd)
        print(f"Running rebuild for {iso} event_code={event_code} event_number={event_number}")
        try:
            run_simple_sql_loop(
                rebuild=True,
                buildAthletes=False,
                start_date=iso,
                end_date=iso,
                skip_coeff_updates=True,
                event_code=event_code,
                all_athletes=False,
                no_volunteers=True,
                leave_athlete_postgres=True,
                Scraper=False,
                no_parkrun_postgres=True,
                refresh_materialized_view=False,
            )
        except Exception as exc:
            print(f"Error on {iso} (event_code={event_code}): {exc}")
            continue


if __name__ == '__main__':
    main()